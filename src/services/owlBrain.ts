/**
 * Find relevant expert answer based on question keywords, with station-aware fallback
 */
export function getExpertOwlAnswer(question: string, studentName: string = 'Ученик', level: number = 1): string {
  const q = question.toLowerCase();

  for (const article of OWL_BANYA_KNOWLEDGE) {
    const hasMatch = article.keywords.some((kw) => q.includes(kw));
    if (hasMatch) {
      return article.generateAnswer(studentName, level);
    }
  }

  // Station-specific guidance if question asks "как пройти станцию" or general question
  const hint = LEVEL_HINTS[level] || LEVEL_HINTS[1];
  return `Ух! 🦉 Приветствую тебя, ${studentName}!\n\nТвой вопрос передан наставнику Антону Ирхину в Telegram-бот школы!\n\n💡 **Подсказка Совы по твоей текущей Станции ${level}:**\n${hint}`;
}
