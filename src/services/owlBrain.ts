/**
 * Find relevant expert answer based on question keywords
 */
export function getExpertOwlAnswer(question: string, studentName: string = 'Ученик', level: number = 1): string | null {
  const q = question.toLowerCase();

  for (const article of OWL_BANYA_KNOWLEDGE) {
    const hasMatch = article.keywords.some((kw) => q.includes(kw));
    if (hasMatch) {
      return article.generateAnswer(studentName, level);
    }
  }

  return null;
}
