export function findSeoPageByPathname(pathname: string): SeoPageConfig | undefined {
  const clean = pathname.replace(/\/+$/, '').toLowerCase();
  if (!clean || clean === '') return undefined;
  return SEO_PAGES.find((page) => page.path.toLowerCase() === clean);
}

export function applyDynamicSeoMeta(params: {
  title: string;
  description: string;
  canonicalPath: string;
}) {
  if (typeof document === 'undefined') return;
  document.title = params.title;

  const canonicalUrl = `${SITE_ORIGIN}${params.canonicalPath.startsWith('/') ? params.canonicalPath : `/${params.canonicalPath}`}`;

  let descMeta = document.querySelector('meta[name="description"]') as HTMLMetaElement | null;
  if (descMeta) {
    descMeta.content = params.description;
  }

  let ogTitle = document.querySelector('meta[property="og:title"]') as HTMLMetaElement | null;
  if (ogTitle) {
    ogTitle.content = params.title;
  }

  let ogDesc = document.querySelector('meta[property="og:description"]') as HTMLMetaElement | null;
  if (ogDesc) {
    ogDesc.content = params.description;
  }

  let ogUrl = document.querySelector('meta[property="og:url"]') as HTMLMetaElement | null;
  if (!ogUrl) {
    ogUrl = document.createElement('meta');
    ogUrl.setAttribute('property', 'og:url');
    document.head.appendChild(ogUrl);
  }
  ogUrl.content = canonicalUrl;

  let canonicalLink = document.querySelector('link[rel="canonical"]') as HTMLLinkElement | null;
  if (canonicalLink) {
    canonicalLink.href = canonicalUrl;
  }
}
